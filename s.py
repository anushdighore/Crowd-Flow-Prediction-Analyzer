        "def gaussian_filter_density(gt_positions: np.ndarray, img_shape: Tuple[int, int], sigma: float = 4.0) -> np.ndarray:\n",
        "    \"\"\"Generate density map using Gaussian filter.\"\"\"\n",
        "    density = np.zeros(img_shape, dtype=np.float32)\n",
        "    \n",
        "    if len(gt_positions) == 0:\n",
        "        return density\n",
        "    \n",
        "    for x, y in gt_positions:\n",
        "        x, y = min(int(x), img_shape[1] - 1), min(int(y), img_shape[0] - 1)\n",
        "        if x >= 0 and y >= 0:\n",
        "            density[y, x] = 1\n",
        "    \n",
        "    density = cv2.GaussianBlur(density, (0, 0), sigmaX=sigma, sigmaY=sigma)\n",
        "    return density\n",
