        "class MultiScaleHead(nn.Module):\n",
        "    \"\"\"Multi-scale density prediction head.\"\"\"\n",
        "    \n",
        "    def __init__(self, in_channels: int = 768, hidden_dim: int = 256):\n",
        "        super().__init__()\n",
        "        \n",
        "        # Feature projection\n",
        "        self.proj = nn.Sequential(\n",
        "            nn.Conv2d(in_channels, hidden_dim, 1),\n",
        "            nn.ReLU(inplace=True),\n",
        "            nn.Conv2d(hidden_dim, hidden_dim, 3, padding=1),\n",
        "            nn.ReLU(inplace=True)\n",
        "        )\n",
        "        \n",
        "        # Multi-scale branches\n",
        "        self.scale1 = nn.Sequential(\n",
        "            nn.Conv2d(hidden_dim, 128, 3, padding=1),\n",
        "            nn.ReLU(inplace=True),\n",
        "            nn.Conv2d(128, 64, 3, padding=1),\n",
        "            nn.ReLU(inplace=True)\n",
        "        )\n",
        "        \n",
        "        self.scale2 = nn.Sequential(\n",
        "            nn.Conv2d(hidden_dim, 128, 5, padding=2),\n",
        "            nn.ReLU(inplace=True),\n",
        "            nn.Conv2d(128, 64, 5, padding=2),\n",
        "            nn.ReLU(inplace=True)\n",
        "        )\n",
        "        \n",
        "        self.scale3 = nn.Sequential(\n",
        "            nn.Conv2d(hidden_dim, 128, 7, padding=3),\n",
        "            nn.ReLU(inplace=True),\n",
        "            nn.Conv2d(128, 64, 7, padding=3),\n",
        "            nn.ReLU(inplace=True)\n",
        "        )\n",
        "        \n",
        "        # Fusion and output\n",
        "        self.fusion = nn.Sequential(\n",
        "            nn.Conv2d(64 * 3, 128, 1),\n",
        "            nn.ReLU(inplace=True),\n",
        "            nn.Conv2d(128, 64, 3, padding=1),\n",
        "            nn.ReLU(inplace=True),\n",
        "            nn.Conv2d(64, 1, 1)\n",
        "        )\n",
        "    \n",
        "    def forward(self, x: torch.Tensor) -> torch.Tensor:\n",
        "        x = self.proj(x)\n",
        "        \n",
        "        # Multi-scale processing\n",
        "        s1 = self.scale1(x)\n",
        "        s2 = self.scale2(x)\n",
        "        s3 = self.scale3(x)\n",
        "        \n",
        "        # Concatenate and fuse\n",
        "        fused = torch.cat([s1, s2, s3], dim=1)\n",
        "        out = self.fusion(fused)\n",
        "        \n",
        "        return out\n",
        "\n",
        "\n",
        "class TMTB(nn.Module):\n",
        "    \"\"\"Token Mixture Transformer with Backbone for crowd counting.\"\"\"\n",
        "    \n",
        "    def __init__(self, backbone_name: str = 'vit_base_patch16_224', pretrained: bool = True):\n",
        "        super().__init__()\n",
        "        \n",
        "        # Import timm here to avoid issues\n",
        "        import timm\n",
        "        \n",
        "        # Vision Transformer backbone\n",
        "        self.backbone = timm.create_model(\n",
        "            backbone_name,\n",
        "            pretrained=pretrained,\n",
        "            num_classes=0,  # Remove classification head\n",
        "            global_pool='',  # No global pooling\n",
        "            img_size=config.input_size[0]\n",
        "        )\n",
        "        \n",
        "        # Get feature dimension\n",
        "        self.feat_dim = self.backbone.num_features\n",
        "        \n",
        "        # Token mixture decoder\n",
        "        self.decoder = nn.TransformerDecoder(\n",
        "            nn.TransformerDecoderLayer(\n",
        "                d_model=self.feat_dim,\n",
        "                nhead=8,\n",
        "                dim_feedforward=2048,\n",
        "                dropout=0.1,\n",
        "                activation='relu',\n",
        "                batch_first=True\n",
        "            ),\n",
        "            num_layers=3\n",
        "        )\n",
        "        \n",
        "        # Learnable queries for decoder\n",
        "        self.query_embed = nn.Parameter(torch.randn(1, 100, self.feat_dim))\n",
        "        \n",
        "        # Feature projection for spatial output\n",
        "        self.proj = nn.Sequential(\n",
        "            nn.Linear(self.feat_dim, self.feat_dim),\n",
        "            nn.ReLU(),\n",
        "            nn.Linear(self.feat_dim, self.feat_dim)\n",
        "        )\n",
        "        \n",
        "        # Multi-scale density head\n",
        "        self.density_head = MultiScaleHead(self.feat_dim, hidden_dim=256)\n",
        "        \n",
        "        # Upsampling to match input size\n",
        "        self.upsample = nn.Sequential(\n",
        "            nn.ConvTranspose2d(1, 32, 4, stride=2, padding=1),\n",
        "            nn.ReLU(inplace=True),\n",
        "            nn.ConvTranspose2d(32, 16, 4, stride=2, padding=1),\n",
        "            nn.ReLU(inplace=True),\n",
        "            nn.ConvTranspose2d(16, 8, 4, stride=2, padding=1),\n",
        "            nn.ReLU(inplace=True),\n",
        "            nn.ConvTranspose2d(8, 1, 4, stride=2, padding=1),\n",
        "            nn.ReLU(inplace=True)\n",
        "        )\n",
        "    \n",
        "    def forward(self, x: torch.Tensor) -> torch.Tensor:\n",
        "        B = x.shape[0]\n",
